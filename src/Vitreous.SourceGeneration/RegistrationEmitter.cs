using System.Text;

namespace Vitreous.SourceGeneration;

/// <summary>
/// Emits the generated C# source for handler registration and the VitreousDispatcher.
/// </summary>
internal static class RegistrationEmitter
{
    internal static string EmitServiceCollectionExtensions(IReadOnlyList<HandlerInfo> handlers)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
        sb.AppendLine("using Vitreous.Abstractions;");
        sb.AppendLine();
        sb.AppendLine("namespace Vitreous;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Source-generated extension method that registers all Vitreous handlers");
        sb.AppendLine("/// discovered at compile time — no runtime assembly scanning.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static partial class VitreousServiceCollectionExtensions");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Registers all source-generated Vitreous handlers and the concrete dispatcher.");
        sb.AppendLine("    /// Call this after <c>AddVitreous()</c>.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static IServiceCollection AddVitreousHandlers(");
        sb.AppendLine("        this IServiceCollection services,");
        sb.AppendLine("        Action<VitreousOptions>? configure = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        services.AddVitreous(configure);");
        sb.AppendLine();

        foreach (var h in handlers)
        {
            var serviceType = GetServiceType(h);
            sb.AppendLine($"        services.TryAddSingleton<{serviceType}, {h.HandlerFullName}>();");
        }

        sb.AppendLine();
        // Register the generated dispatcher, replacing the reflection fallback
        sb.AppendLine("        // Replace reflection-based fallbacks with the source-generated dispatcher");
        sb.AppendLine("        services.RemoveAll<ISender>();");
        sb.AppendLine("        services.RemoveAll<IPublisher>();");
        sb.AppendLine("        services.AddSingleton<VitreousDispatcher>();");
        sb.AppendLine("        services.AddSingleton<ISender>(sp => sp.GetRequiredService<VitreousDispatcher>());");
        sb.AppendLine("        services.AddSingleton<IPublisher>(sp => sp.GetRequiredService<VitreousDispatcher>());");
        sb.AppendLine();
        sb.AppendLine("        return services;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    internal static string EmitDispatcher(IReadOnlyList<HandlerInfo> handlers)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using Vitreous.Abstractions;");
        sb.AppendLine("using Vitreous.Internal;");
        sb.AppendLine();
        sb.AppendLine("namespace Vitreous;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Source-generated dispatcher — zero reflection, fully AOT-compatible.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public sealed class VitreousDispatcher : ISender, IPublisher");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly IServiceProvider _services;");
        sb.AppendLine();
        sb.AppendLine("    public VitreousDispatcher(IServiceProvider services)");
        sb.AppendLine("        => _services = services;");
        sb.AppendLine();

        // ISender.Send<TResult>(ICommand<TResult>) — dispatches by concrete type
        EmitCommandWithResultSend(sb, handlers);

        // ISender.Send(ICommand) — dispatches by concrete type (void commands)
        EmitVoidCommandSend(sb, handlers);

        // ISender.Send<TResult>(IQuery<TResult>)
        EmitQuerySend(sb, handlers);

        // IPublisher.Publish<TNotification>
        EmitPublish(sb, handlers);

        sb.AppendLine("}");

        return sb.ToString();
    }

    // -------------------------------------------------------------------------
    // Send<TResult>(ICommand<TResult>)
    // -------------------------------------------------------------------------

    private static void EmitCommandWithResultSend(StringBuilder sb, IReadOnlyList<HandlerInfo> handlers)
    {
        var commands = handlers.Where(h => h.Kind == HandlerKind.Command).ToList();

        sb.AppendLine("    /// <inheritdoc/>");
        sb.AppendLine("    public async ValueTask<Result<TResult>> Send<TResult>(");
        sb.AppendLine("        ICommand<TResult> command,");
        sb.AppendLine("        CancellationToken ct = default)");
        sb.AppendLine("    {");

        if (commands.Count == 0)
        {
            sb.AppendLine("        throw new InvalidOperationException(");
            sb.AppendLine("            $\"No handler registered for command '{command.GetType().Name}'.\");");
        }
        else
        {
            // Use if/else chain — switch can't unify different ValueTask<Result<T>> types
            foreach (var h in commands)
            {
                sb.AppendLine($"        if (command is {h.MessageFullName} __c_{Sanitize(h.MessageTypeName)})");
                sb.AppendLine($"            return (Result<TResult>)(object)await ExecuteCommand<{h.MessageFullName}, {h.ResultFullName}>(__c_{Sanitize(h.MessageTypeName)}, ct);");
            }
            sb.AppendLine("        throw new InvalidOperationException(");
            sb.AppendLine("            $\"No handler registered for command '{command.GetType().Name}'.\");");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        // Helper method
        sb.AppendLine("    private ValueTask<Result<TResult>> ExecuteCommand<TCommand, TResult>(");
        sb.AppendLine("        TCommand command, CancellationToken ct)");
        sb.AppendLine("        where TCommand : ICommand<TResult>");
        sb.AppendLine("    {");
        sb.AppendLine("        var handler = _services.GetRequiredService<ICommandHandler<TCommand, TResult>>();");
        sb.AppendLine("        var behaviors = _services.GetServices<IPipelineBehavior<TCommand, TResult>>();");
        sb.AppendLine("        MessageHandlerDelegate<TCommand, TResult> terminal = handler.Handle;");
        sb.AppendLine("        return PipelineExecutor.Execute(command, terminal, behaviors, ct);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    // -------------------------------------------------------------------------
    // Send(ICommand) — void commands
    // -------------------------------------------------------------------------

    private static void EmitVoidCommandSend(StringBuilder sb, IReadOnlyList<HandlerInfo> handlers)
    {
        var voidCommands = handlers.Where(h => h.Kind == HandlerKind.VoidCommand).ToList();

        sb.AppendLine("    /// <inheritdoc/>");
        sb.AppendLine("    public async ValueTask<Result> Send(ICommand command, CancellationToken ct = default)");
        sb.AppendLine("    {");

        if (voidCommands.Count == 0)
        {
            sb.AppendLine("        throw new InvalidOperationException(");
            sb.AppendLine("            $\"No handler registered for command '{command.GetType().Name}'.\");");
        }
        else
        {
            foreach (var h in voidCommands)
            {
                sb.AppendLine($"        if (command is {h.MessageFullName} __vc_{Sanitize(h.MessageTypeName)})");
                sb.AppendLine($"            return await ExecuteVoidCommand<{h.MessageFullName}>(__vc_{Sanitize(h.MessageTypeName)}, ct);");
            }
            sb.AppendLine("        throw new InvalidOperationException(");
            sb.AppendLine("            $\"No handler registered for command '{command.GetType().Name}'.\");");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    private ValueTask<Result> ExecuteVoidCommand<TCommand>(");
        sb.AppendLine("        TCommand command, CancellationToken ct)");
        sb.AppendLine("        where TCommand : ICommand");
        sb.AppendLine("    {");
        sb.AppendLine("        var handler = _services.GetRequiredService<ICommandHandler<TCommand>>();");
        sb.AppendLine("        var behaviors = _services.GetServices<IPipelineBehavior<TCommand, Unit>>();");
        sb.AppendLine("        CommandHandlerDelegate<TCommand> terminal = handler.Handle;");
        sb.AppendLine("        return PipelineExecutor.ExecuteVoid(command, terminal, behaviors, ct);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    // -------------------------------------------------------------------------
    // Send<TResult>(IQuery<TResult>)
    // -------------------------------------------------------------------------

    private static void EmitQuerySend(StringBuilder sb, IReadOnlyList<HandlerInfo> handlers)
    {
        var queries = handlers.Where(h => h.Kind == HandlerKind.Query).ToList();

        sb.AppendLine("    /// <inheritdoc/>");
        sb.AppendLine("    public async ValueTask<Result<TResult>> Send<TResult>(");
        sb.AppendLine("        IQuery<TResult> query,");
        sb.AppendLine("        CancellationToken ct = default)");
        sb.AppendLine("    {");

        if (queries.Count == 0)
        {
            sb.AppendLine("        throw new InvalidOperationException(");
            sb.AppendLine("            $\"No handler registered for query '{query.GetType().Name}'.\");");
        }
        else
        {
            foreach (var h in queries)
            {
                sb.AppendLine($"        if (query is {h.MessageFullName} __q_{Sanitize(h.MessageTypeName)})");
                sb.AppendLine($"            return (Result<TResult>)(object)await ExecuteQuery<{h.MessageFullName}, {h.ResultFullName}>(__q_{Sanitize(h.MessageTypeName)}, ct);");
            }
            sb.AppendLine("        throw new InvalidOperationException(");
            sb.AppendLine("            $\"No handler registered for query '{query.GetType().Name}'.\");");
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    private ValueTask<Result<TResult>> ExecuteQuery<TQuery, TResult>(");
        sb.AppendLine("        TQuery query, CancellationToken ct)");
        sb.AppendLine("        where TQuery : IQuery<TResult>");
        sb.AppendLine("    {");
        sb.AppendLine("        var handler = _services.GetRequiredService<IQueryHandler<TQuery, TResult>>();");
        sb.AppendLine("        var behaviors = _services.GetServices<IPipelineBehavior<TQuery, TResult>>();");
        sb.AppendLine("        MessageHandlerDelegate<TQuery, TResult> terminal = handler.Handle;");
        sb.AppendLine("        return PipelineExecutor.Execute(query, terminal, behaviors, ct);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    // -------------------------------------------------------------------------
    // Publish<TNotification>
    // -------------------------------------------------------------------------

    private static void EmitPublish(StringBuilder sb, IReadOnlyList<HandlerInfo> handlers)
    {
        var notifications = handlers
            .Where(h => h.Kind == HandlerKind.Notification)
            .GroupBy(h => h.MessageFullName)
            .ToList();

        sb.AppendLine("    /// <inheritdoc/>");
        sb.AppendLine("    public ValueTask Publish<TNotification>(");
        sb.AppendLine("        TNotification notification,");
        sb.AppendLine("        CancellationToken ct = default)");
        sb.AppendLine("        where TNotification : INotification");
        sb.AppendLine("    {");
        sb.AppendLine("        // Delegate to the strongly-typed overload via the sequential publisher");
        sb.AppendLine("        var publisher = _services.GetRequiredService<SequentialPublisher>();");
        sb.AppendLine("        return publisher.Publish(notification, ct);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    // -------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------

    private static string GetServiceType(HandlerInfo h) => h.Kind switch
    {
        HandlerKind.Command =>
            $"ICommandHandler<{h.MessageFullName}, {h.ResultFullName}>",
        HandlerKind.VoidCommand =>
            $"ICommandHandler<{h.MessageFullName}>",
        HandlerKind.Query =>
            $"IQueryHandler<{h.MessageFullName}, {h.ResultFullName}>",
        HandlerKind.Notification =>
            $"INotificationHandler<{h.MessageFullName}>",
        _ => throw new ArgumentOutOfRangeException(nameof(h.Kind))
    };

    /// <summary>
    /// Makes a type name safe for use as a C# local variable identifier.
    /// </summary>
    private static string Sanitize(string typeName) =>
        typeName.Replace('.', '_').Replace('<', '_').Replace('>', '_').Replace(',', '_').Replace(' ', '_');
}
